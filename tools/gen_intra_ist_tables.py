"""Transcribe the AV2 v1.0.0 8x8 secondary-transform tables.

Use the spec HTML (spec-v1.html) and its ist_8x8_kernel.h and stx_scan_map.h
attachments from https://av2.aomedia.org/v1.0.0/. The decoder's set-to-kernel
tables are inverted here to map encoder-selected kernels to wire symbols.
"""
import argparse
import html
from math import prod
import re
from pathlib import Path

from gen_entropy_models import initializer


def integers(text, name):
    start = re.search(r'^\s*' + name + r'\s*\[', text, re.MULTILINE)
    if start is None:
        raise ValueError(name)
    return [int(value) for value in re.findall(r'-?\d+', initializer(text[start.start():], name))]


def array(name, kind, dimensions, values):
    assert len(values) == prod(dimensions)

    def nest(shape, offset=0, depth=0):
        indent = '    ' * depth
        if len(shape) == 1:
            return indent + '{' + ', '.join(map(str, values[offset:offset+shape[0]])) + '}'
        stride = prod(shape[1:])
        entries = [nest(shape[1:], offset + i*stride, depth+1) for i in range(shape[0])]
        return indent + '{\n' + ',\n'.join(entries) + '\n' + indent + '}'

    suffix = ''.join(f'[{n}]' for n in dimensions)
    return f'static const {kind} {name}{suffix} = {nest(dimensions)};\n'


def mode_symbols(spec, name, sets):
    values = integers(spec, name)
    assert len(values) == 12 * sets
    return [values[i:i+sets].index(j) for i in range(0, len(values), sets) for j in range(sets)]


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('spec_dir', type=Path)
    p.add_argument('source_dir', type=Path, help='SVT Source/Lib directory')
    a = p.parse_args()
    spec = html.unescape(re.sub(r'<[^>]+>', '', (a.spec_dir/'spec-v1.html').read_text(encoding='utf-8')))
    preamble = '/* AV2 v1.0.0 normative tables. Generated by tools/gen_intra_ist_tables.py. */\n\n'
    kernels = integers((a.spec_dir/'ist_8x8_kernel.h').read_text(), 'Ist_8x8_Kernel')
    mapping = integers((a.spec_dir/'stx_scan_map.h').read_text(), 'Stx_Scan_Map')
    scans = integers(spec, 'Stx_Scan_Order_8x8')
    transforms = (
        array('ist_8x8_scan', 'uint8_t', (64,), scans) +
        array('ist_8x8_map', 'uint8_t', (11, 3, 48), mapping) +
        array('ist_8x8_kernel', 'int16_t', (11, 3, 32, 48), kernels)
    )
    modes = (
        array('ist_dct_set_symbol', 'uint8_t', (12, 7), mode_symbols(spec, 'Inv_Most_Probable_Stx_Mapping', 7)) +
        array('ist_adst_set_symbol', 'uint8_t', (12, 4), mode_symbols(spec, 'Inv_Most_Probable_Stx_Mapping_Adst', 4))
    )
    (a.source_dir/'Transform/intra_ist_data.h').write_bytes((preamble + transforms).encode('ascii'))
    (a.source_dir/'EntropyCoding/intra_ist_modes.h').write_bytes((preamble + modes).encode('ascii'))


if __name__ == '__main__':
    main()
